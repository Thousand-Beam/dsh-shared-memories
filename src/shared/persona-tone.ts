/** 特质排序规则：只留有限数值、按强弱降序、最多 16 项（16 轴就是上限）。 */
export function topTraits(
  traits: Readonly<Record<string, number>>,
  limit = 16,
): Array<[string, number]> {
  return Object.entries(traits)
    .filter(([, value]) => Number.isFinite(value))
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
}

/** 倾向行：`- 倾向（0 到 1 的内部刻度，高=更明显、低=更收敛）：curiosity 0.82 · …` */
export function renderTraitLine(traits: Readonly<Record<string, number>>, limit = 16): string {
  const entries = topTraits(traits, limit)
  if (entries.length === 0) return '- 倾向：（尚未形成，按下面的行为基调行事即可）'
  return `- 倾向（0 到 1 的内部刻度，高=更明显、低=更收敛）：${entries
    .map(([key, value]) => `${key} ${value.toFixed(2)}`)
    .join(' · ')}`
}
